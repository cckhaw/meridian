// Embeds migrations/*.sql into @meridian/core so the app has no runtime filesystem dependency
// (Next.js/Vercel bundles do not ship loose .sql files). Run: pnpm --filter @meridian/db embed
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = new URL('./migrations/', import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} },`).join('\n');
const out = `// GENERATED by packages/db/scripts-embed.mjs from packages/db/migrations. Do not edit.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = [\n${body}\n];\n`;
writeFileSync(new URL('../core/src/migrations.generated.ts', import.meta.url), out);
console.log('embedded', files.join(', '));
